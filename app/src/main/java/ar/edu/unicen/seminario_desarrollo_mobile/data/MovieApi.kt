package ar.edu.unicen.seminario_desarrollo_mobile.data

import ar.edu.unicen.seminario_desarrollo_mobile.data.dto.MovieDetailDto
import ar.edu.unicen.seminario_desarrollo_mobile.data.dto.MovieListResponseDto
import retrofit2.Response
import retrofit2.http.GET
import retrofit2.http.Path
import retrofit2.http.Query

interface MovieApi {

    @GET("movie/popular")
    suspend fun getPopularMovies(
        @Query("api_key") apiKey: String,
        @Query("language") language: String = "es-ES"
    ): Response<MovieListResponseDto>

    @GET("movie/{movie_id}")
    suspend fun getMovieDetail(
        @Path("movie_id") movieId: Int,
        @Query("api_key") apiKey: String,
        @Query("language") language: String = "es-ES"
    ): Response<MovieDetailDto>

    @GET("search/movie")
    suspend fun searchMovies(
        @Query("query") query: String,
        @Query("api_key") apiKey: String,
        @Query("language") language: String = "es-ES"
    ): Response<MovieListResponseDto>
}